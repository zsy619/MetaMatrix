/** 归一化：去掉变体选择符与零宽连接符，让 🏳 与 🏳️ 视为同一个图标。 */
function normalize(char: string): string {
  return char.replace(/[\uFE0E\uFE0F\u200D]/g, '')
}

/**
 * 构建分组：按顺序遍历，"常用" 优先占位，其余分组跳过已占用的字符，
 * 保证任意一个图标在全库只出现一次。
 */
function buildGroups(): IconGroup[] {
  const taken = new Set<string>()
  const takenNames = new Set<string>()
  const result: IconGroup[] = []
  for (const group of RAW_GROUPS) {
    const items: IconItem[] = []
    for (const item of group.items) {
      const key = normalize(item.char)
      if (!key || taken.has(key)) continue
      // 同名图标（如 ⬤ 与 ●）视觉上等价，只保留先出现的一个
      const nameKey = item.name.trim().toLowerCase()
      if (!nameKey || takenNames.has(nameKey)) continue
      taken.add(key)
      takenNames.add(nameKey)
      items.push(item)
    }
    if (items.length) result.push({ key: group.key, label: group.label, items })
  }
  return result
}

export const ICON_GROUPS: IconGroup[] = buildGroups()

/** 图标总数，用于「已收录 N 个图标」展示。 */
export const ICON_TOTAL = ICON_GROUPS.reduce((sum, g) => sum + g.items.length, 0)

/** 扁平索引：字符 → 名称，用于搜索。 */
export const ICON_SEARCH: IconItem[] = ICON_GROUPS.flatMap((g) => g.items)
